"use strict";
// Variable Annotation in TypeScript
// Declaring a string variable
let studentName = "Rahul";
// Declaring a number variable
let age = 20;
// Declaring a boolean variable
let isStudent = true;
// Printing the values
console.log("Name:", studentName);
console.log("Age:", age);
console.log("Student:", isStudent);
/*
Output:
Name: Rahul
Age: 20
Student: true
*/ 
